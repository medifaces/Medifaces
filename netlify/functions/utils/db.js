export function getDatabase() {
  const dbUrl = process.env.DATABASE_URL;
  if (dbUrl && dbUrl.startsWith('postgres')) {
    try {
      const sql = neon(dbUrl);
      return { isPostgres: true, sql, memory: inMemoryDB };
    } catch (e) {
      console.warn('Neon connection initialization fallback to memory:', e);
      return { isPostgres: false, memory: inMemoryDB };
    }
  }
  return { isPostgres: false, memory: inMemoryDB };
}

